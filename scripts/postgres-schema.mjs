// Production uses Postgres; local development uses SQLite (zero setup).
// Prisma can't switch providers by environment, so the deploy build generates a Postgres copy
// of prisma/schema.prisma at prisma/generated/postgres.prisma. Edit only prisma/schema.prisma.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
const out = src.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
if (out === src) {
  console.error('postgres-schema: expected provider = "sqlite" in prisma/schema.prisma');
  process.exit(1);
}
// Hosted Postgres (e.g. Neon via Vercel) gives a pooled DATABASE_URL for the app and a direct
// DATABASE_URL_UNPOOLED. Schema changes (prisma db push) must use the direct connection.
const directVar = ["DATABASE_URL_UNPOOLED", "DIRECT_URL"].find((v) => process.env[v]);
const final = directVar
  ? out.replace(/(url\s*=\s*env\("DATABASE_URL"\))/, `$1\n  directUrl = env("${directVar}")`)
  : out;
if (directVar) console.log(`postgres-schema: using ${directVar} for schema changes`);
mkdirSync("prisma/generated", { recursive: true });
writeFileSync(
  "prisma/generated/postgres.prisma",
  "// GENERATED by scripts/postgres-schema.mjs from prisma/schema.prisma. Do not edit.\n" + final,
);
console.log("postgres-schema: wrote prisma/generated/postgres.prisma");
